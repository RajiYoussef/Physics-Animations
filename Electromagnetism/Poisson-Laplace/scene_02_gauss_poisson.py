"""Run this file in PyCharm to render the second scene."""
import settings
from manim import *
from support import *
from science_anim.presentation.choreography import emphasize


class GaussPoisson(OpeningScene):
    def construct(self):
        d=SlabDiagram()
        d.vc.set_value(-6)
        self.beat('same_field_gaussian_volume')
        self.say('لِنأخذ حيزاً صغيراً، ولنلاحظ مقدار التدفق الذي يدخل إليه ومقدار التدفق الذي يخرج منه')
        self.play(FadeIn(d.field()),Create(d.levels),FadeIn(d.arrows),run_time=2)
        title=VGroup(tex(r'\mathbf{D}=\epsilon\mathbf{E}',36),ar('الإزاحة الكهربائية D',25),ar('السماحية الكهربائية',23),tex(r'\epsilon=1',28)).arrange(DOWN,buff=.28).move_to([3.4,.7,0])
        self.play(FadeIn(title),run_time=1.5)
        box=Rectangle(width=2.5,height=d.Y(2)-d.Y(1),stroke_color=YELLOW,stroke_width=2.5,fill_color=YELLOW,fill_opacity=.05).move_to([-3.3,d.Y(1.5),0])
        top=Line([-4.55,d.Y(2),0],[-2.05,d.Y(2),0],color=YELLOW,stroke_width=4)
        bottom=Line([-4.55,d.Y(1),0],[-2.05,d.Y(1),0],color=YELLOW,stroke_width=4)
        shape=ar('حجم غاوسي صغير',24).move_to([-3.3,-3.1,0])
        self.play(Create(box),FadeIn(shape),run_time=2)
        heights=VGroup(tex('y=2',22,color=GREY).move_to([-6.05,d.Y(2),0]),tex('y=1',22,color=GREY).move_to([-6.05,d.Y(1),0]))
        self.add(heights)
        normals=VGroup(Arrow([-4.3,d.Y(2),0],[-4.3,d.Y(2)+.65,0],buff=0,color=YELLOW),Arrow([-4.3,d.Y(1),0],[-4.3,d.Y(1)-.65,0],buff=0,color=YELLOW))
        nlabels=VGroup(tex(r'\hat{n}',24,color=YELLOW).next_to(normals[0],LEFT,buff=.1),tex(r'\hat{n}',24,color=YELLOW).next_to(normals[1],LEFT,buff=.1))
        self.play(GrowArrow(normals[0]),GrowArrow(normals[1]),FadeIn(nlabels),run_time=2)
        self.wait(1.5)
        self.play(FadeOut(title),run_time=.7)
        self.beat('net_flux_and_charge')
        self.say('نعرِف التدفق إلى الخارج بأنه موجب، والتدفق إلى الداخل بأنه سالب')
        counts=VGroup()
        for ypos,sym,y in [(1.6,r'D_y(2)=',2),(.75,r'D_y(1)=',1)]:
            number=DecimalNumber(d.E(y),num_decimal_places=2,mob_class=Text,font_size=29,color=BLUE)
            row=VGroup(tex(sym,31),number).arrange(RIGHT,buff=.22).move_to([3.4,ypos,0])
            number.add_updater(lambda m,y=y:m.set_value(d.E(y)))
            counts.add(row)
        dimensions=VGroup(tex(r'A=1,\quad\Delta y=1',27),tex(r'\Phi_D=A[D_y(2)-D_y(1)]',29)).arrange(DOWN,buff=.4).move_to([3.4,-.55,0])
        net=DecimalNumber(0,num_decimal_places=2,mob_class=Text,font_size=31,color=YELLOW)
        netrow=VGroup(tex(r'\Phi_D=',32,color=YELLOW),net).arrange(RIGHT,buff=.25).move_to([3.4,-1.9,0])
        net.add_updater(lambda m:m.set_value(d.E(2)-d.E(1)))
        self.play(FadeIn(counts),FadeIn(dimensions),FadeIn(netrow),run_time=2)
        self.play(Create(top),run_time=.7)
        self.play(ShowPassingFlash(Line([-3.1,d.Y(1.5),0],[-3.1,d.Y(2)+.65,0],color=YELLOW,stroke_width=5),time_width=.35),run_time=2)
        self.play(Create(bottom),run_time=.7)
        self.play(ShowPassingFlash(Line([-3.1,d.Y(1)-.65,0],[-3.1,d.Y(1.5),0],color=YELLOW,stroke_width=5),time_width=.35),run_time=2)
        self.say('إذا كانت الشحنة المحصورة داخل السطح صفرا، فإن صافي التدفق عبر هذا السطح يكون صفرا')
        emphasize(self,netrow,color=YELLOW,run_time=1.4)
        self.wait(1.5)
        interior=VGroup(*[VGroup(Circle(.10,color=YELLOW,stroke_width=1.5),tex('+',17,color=YELLOW)).move_to([x,d.Y(y),0]) for x,y in [(-4.8,.45),(-3.4,.45),(-1.7,.45),(-4.8,1.55),(-3.4,1.55),(-1.7,1.55),(-4.8,2.55),(-3.4,2.55),(-1.7,2.55)]])
        self.say('إذا أضفنا شحنات موجبة داخل الحجم المغلق')
        self.play(d.rho.animate.set_value(1),FadeIn(interior),run_time=4)
        rho=tex(r'\rho_f=1',29,color=YELLOW).move_to([-3.2,-2.85,0])
        density_label=ar('كثافة الشحنة الحرة',22,color=YELLOW).move_to([-3.2,-3.3,0])
        self.play(FadeOut(shape),FadeIn(rho),FadeIn(density_label),run_time=1)
        self.say('مع وجود تلك الكمية من الشحنة الموجبة المحصورة، يصبح التدفق الصافي نحو الخارج موجب')
        charge=tex(r'Q_f=\rho_f A\Delta y=1',29,color=YELLOW).move_to([3.4,-2.8,0])
        self.play(FadeIn(charge),run_time=1.5)
        emphasize(self,netrow,color=YELLOW,run_time=1.5)
        self.wait(1.5)
        self.beat('gauss_law_to_potential')
        self.play(FadeOut(VGroup(counts,dimensions,netrow,charge)),run_time=1)
        self.say('يأتي هذا وفق لقانون غاوس الذي يربط صافي التدفق عبر سطح ما بالشحنة المحصورة داخله')
        equation=tex(r'\oint_S\mathbf{D}\cdot\hat{n}\,dS=Q_f',35,width=6).move_to([3.4,1.15,0])
        self.play(FadeIn(equation),run_time=1.5)
        self.play(ShowPassingFlash(top.copy(),time_width=.4),ShowPassingFlash(bottom.copy(),time_width=.4),run_time=2)
        local=ar('الصيغة التفاضلية لقانون غاوس',24).move_to([3.4,-.1,0])
        self.play(FadeIn(local),run_time=1)
        next_eq=tex(r'\nabla\cdot\mathbf{D}=\rho_f',39,width=6).move_to(equation)
        self.play(FadeTransform(equation,next_eq),run_time=1.3);equation=next_eq
        self.play(box.animate.set_stroke(width=4),run_time=1.2)
        self.wait(1.5)
        #self.say('نعوض عن D بالعلاقة D=εE ')
        #self.say('ثم نستخدم العلاقة E=-∇V')
        #self.say('نعوّض عن D بالعلاقة D=εE، ثم نستخدم العلاقة E=-∇V')
        self.say('\u202Bنعوّض عن \u2066D\u2069 بالعلاقة \u2066D=εE\u2069، ثم نستخدم العلاقة \u2066E=-∇V\u2069\u202C')

        relation=tex(r'\mathbf{D}=\epsilon\mathbf{E}',32).move_to([3.4,-1.2,0])
        self.play(FadeOut(local),FadeIn(relation),run_time=1)
        next_eq=tex(r'\nabla\cdot(\epsilon\mathbf{E})=\rho_f',36,width=6).move_to(equation)
        self.play(TransformFromCopy(relation,next_eq),FadeOut(equation),run_time=1.7);equation=next_eq
        self.play(Indicate(d.arrows,color=BLUE,scale_factor=1.03),run_time=1.7)
        next_relation=tex(r'\mathbf{E}=-\nabla V',34).move_to(relation)
        self.play(FadeTransform(relation,next_relation),run_time=1.2);relation=next_relation
        next_eq=tex(r'\nabla\cdot(-\epsilon\nabla V)=\rho_f',35,width=6).move_to(equation)
        self.play(TransformFromCopy(relation,next_eq),FadeOut(equation),run_time=1.7);equation=next_eq
        self.wait(1.2)
        next_eq=tex(r'\nabla\cdot(\epsilon\nabla V)=-\rho_f',35,width=6).move_to(equation)
        self.play(FadeTransform(equation,next_eq),run_time=1.5);equation=next_eq
        self.say('إذا كانت السماحية مقدار ثابت في جميع أنحاء المنطقة، فيمكننا إخراجها خارج مؤثر التباعد')
        const=VGroup(tex(r'\epsilon=\mathrm{constant}',29),ar('وسط متجانس',24)).arrange(DOWN,buff=.2).move_to([3.4,-1.2,0])
        self.play(FadeOut(relation),FadeIn(const),run_time=1)
        next_eq=tex(r'\epsilon\nabla^2 V=-\rho_f',39,width=6).move_to(equation)
        self.play(FadeTransform(equation,next_eq),run_time=1.5);equation=next_eq
        self.wait(1.3)
        next_eq=tex(r'\nabla^2V=-\frac{\rho_f}{\epsilon}',43,width=6).move_to(equation)
        self.play(FadeTransform(equation,next_eq),run_time=1.5);equation=next_eq
        poisson=ar('معادلة بواسون',28,color=YELLOW).move_to([3.4,.1,0])
        self.play(FadeIn(poisson),run_time=1)
        self.wait(2)
        self.beat('poisson_to_laplace')
        self.say('تربط معادلة بواسون بين كثافة الشحنة وانحناء مخطط الجهد')
        self.play(FadeOut(VGroup(equation,const,poisson,normals,nlabels,box,top,bottom)),run_time=1)
        self.play(Create(d.axes),FadeIn(d.axis_labels),FadeIn(d.ticks),Create(d.curve),run_time=2)
        relation=tex(r'\frac{d^2V}{dy^2}=-\frac{\rho_f}{\epsilon}=-1',33,width=6).move_to([3.4,-2.8,0])
        self.play(FadeIn(relation),run_time=1.3)
        self.play(d.probe.animate.set_value(2.7),FadeIn(d.graph_dot),run_time=3)
        self.say('إذا كانت المنطقة خالية من الشحنات، فإن معادلة بواسون تؤول إلى معادلة لابلاس')
        self.play(FadeOut(relation),run_time=.7)
        self.play(d.rho.animate.set_value(0),FadeOut(interior),FadeOut(rho),FadeOut(density_label),run_time=5)
        laplace=tex(r'\rho_f=0\quad\Rightarrow\quad\nabla^2V=0',35,width=6).move_to([3.4,-2.8,0])
        self.play(FadeIn(laplace),run_time=1.7)
        self.say('انعدام الشحنة الحرة داخل المنطقة لا يمنع وجود مجال فيها.')
        self.play(Indicate(d.arrows,color=YELLOW,scale_factor=1.06),run_time=2)
        self.play(Indicate(d.charges,color=YELLOW,scale_factor=1.05),run_time=2)
        self.wait(2.5)
        self.finish()


if __name__=='__main__':
    settings.run(GaussPoisson)

