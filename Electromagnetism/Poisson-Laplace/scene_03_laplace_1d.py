from manim import *
from support34 import *
from settings34 import run


class LaplaceOneDimension(LessonScene):
    def construct(self):
        d = PlatePlot()
        self.beat('geometry_and_known_values')
        self.say('كيف نجد الجهد بين اللوحين؟')
        self.play(Create(d.plates), Create(d.baseline), FadeIn(d.ends), run_time=2.4)
        self.play(FadeIn(d.left_label), FadeIn(d.right_label), run_time=1.5)
        unknown = VGroup(*[tex(r'?',34,YELLOW).move_to(d.P(x)) for x in (.6,1.5,2.4)])
        self.play(LaggedStart(*[FadeIn(m,shift=UP*.15) for m in unknown],lag_ratio=.5),run_time=2)
        assumptions = VGroup(ar('وسط متجانس',26), ar('لا شحنة حرة بين اللوحين',26),tex(r'V=V(x)',35,BLUE)).arrange(DOWN,buff=.4).move_to([3.5,.4,0])
        self.play(FadeIn(assumptions),run_time=1.5)
        self.play(Indicate(d.plates[0],color=GREEN),Indicate(d.plates[1],color=BLUE),run_time=2)
        self.wait(1.5)
        self.beat('two_integrations')
        self.play(FadeOut(VGroup(d.physical(),unknown,assumptions)),run_time=1.2)
        self.say('إذا كانت المشتقة الثانية صفر، فإن الميل يكون ثابت')
        left = tex(r'V(0)=V_0',31,GREEN).move_to([-4.5,2.35,0])
        right = tex(r'V(L)=V_1',31,BLUE).move_to([4.5,2.35,0])
        eq0 = tex(r'\frac{d^2V}{dx^2}=0',50).move_to([-4.45,.7,0])
        eq1 = tex(r'\frac{dV}{dx}=B',50,YELLOW).move_to([0,.7,0])
        eq2 = tex(r'V(x)=A+Bx',36,BLUE).move_to([4.35,.7,0])
        a1 = Arrow([-2.6,.7,0],[-1.8,.7,0],buff=0,color=GREY)
        a2 = Arrow([1.5,.7,0],[2.15,.7,0],buff=0,color=GREY)
        self.play(FadeIn(left),FadeIn(right),Write(eq0),run_time=2.5)
        self.play(GrowArrow(a1),TransformFromCopy(eq0,eq1),run_time=2.5)
        self.play(FadeIn(ar('التكامل الأول',24).move_to([-2.2,1.65,0])),run_time=.7)
        self.play(GrowArrow(a2),TransformFromCopy(eq1,eq2),run_time=2.5)
        self.play(FadeIn(ar('التكامل الثاني',24).move_to([1.95,1.65,0])),run_time=.7)
        tiny_axes, tiny_frame = graph_axes([0,-1.9,0],width=6,height=1.25,ymax=10)
        tiny_frame[-1].set_opacity(.2)
        family = VGroup(*[Line(tiny_axes.c2p(0,a),tiny_axes.c2p(3,a+3*b),color=c,stroke_width=3) for a,b,c in [(0,1,GREY),(0,2,BLUE),(2,2,YELLOW)]])
        self.play(Create(tiny_frame),LaggedStart(*[Create(m) for m in family],lag_ratio=.5),run_time=3)
        self.play(Indicate(eq2,color=BLUE),run_time=1.5)
        self.wait(1)
        self.beat('boundary_substitutions')
        self.play(*[FadeOut(m) for m in list(self.mobjects) if m not in [self.caption,left,right]],run_time=1)
        self.say('نستخدم جهد كل لوح لتحديد الثابتين')
        general = tex(r'V(x)=A+Bx',48).move_to([0,1.45,0])
        first = tex(r'V(0)=A+B\cdot0=V_0',40).move_to([0,.15,0])
        aval = tex(r'A=V_0',42,GREEN).move_to([0,-1.1,0])
        self.play(Write(general),run_time=1.7)
        self.play(TransformFromCopy(left,first),run_time=2.2)
        self.play(TransformFromCopy(first,aval),Circumscribe(left,color=GREEN),run_time=2)
        self.wait(1)
        second = tex(r'V(L)=V_0+BL=V_1',41).move_to([0,.15,0])
        bval = tex(r'B=\frac{V_1-V_0}{L}',44,BLUE).move_to([0,-1.25,0])
        self.play(FadeOut(first),aval.animate.scale(.75).move_to([-4.5,1.3,0]),TransformFromCopy(right,second),run_time=2.2)
        self.play(TransformFromCopy(second,bval),Circumscribe(right,color=BLUE),run_time=2)
        self.wait(1)
        result = tex(r'V(x)=V_0+\frac{V_1-V_0}{L}x',51,YELLOW).move_to([0,-2.65,0])
        self.play(TransformFromCopy(VGroup(general,aval,bval),result),run_time=2.5)
        self.play(Circumscribe(result,color=YELLOW),run_time=1.6)
        self.wait(1)
        self.beat('numerical_solution_and_probe')
        self.play(*[FadeOut(m) for m in list(self.mobjects) if m is not self.caption],run_time=1.1)
        self.say('المسافة بين اللوحين 3 أمتار، وفرق الجهد بينهما 6 فولت')
        self.play(FadeIn(d.physical()),Create(d.frame),run_time=2.2)
        self.play(Create(d.curve),run_time=2.5)
        formula = tex(r'V(x)=\left(2\;\mathrm{V/m}\right)x',30,BLUE).move_to([-3.4,-3.35,0])
        self.play(FadeIn(d.probes()),FadeIn(formula),run_time=1.4)
        self.play(d.probe.animate.set_value(1),run_time=3)
        p1 = Dot(d.axes.c2p(1,2),color=YELLOW,radius=.065)
        l1 = tex(r'(1,2)',23,YELLOW).next_to(p1,UP+LEFT,buff=.12)
        self.play(FadeIn(p1),FadeIn(l1),run_time=.8)
        self.play(d.probe.animate.set_value(2),run_time=3)
        p2 = Dot(d.axes.c2p(2,4),color=YELLOW,radius=.065)
        l2 = tex(r'(2,4)',23,YELLOW).next_to(p2,UP+LEFT,buff=.12)
        self.play(FadeIn(p2),FadeIn(l2),run_time=.8)
        self.play(d.probe.animate.set_value(3),run_time=3)
        self.play(d.probe.animate.set_value(.4),run_time=3)
        self.beat('slope_and_electric_field')
        self.say('يتغير الجهد بمقدار 2 فولت لكل متر بين اللوحين')
        self.play(FadeOut(VGroup(p1,p2,l1,l2)),run_time=.6)
        triangle = VGroup(DashedLine(d.axes.c2p(1,2),d.axes.c2p(2,2),color=YELLOW),DashedLine(d.axes.c2p(2,2),d.axes.c2p(2,4),color=YELLOW))
        tri_labels = VGroup(tex(r'\Delta x=1\;\mathrm{m}',23,YELLOW).next_to(triangle[0],DOWN,buff=.12),tex(r'\Delta V=2\;\mathrm{V}',23,YELLOW).next_to(triangle[1],RIGHT,buff=.12))
        self.play(Create(triangle[0]),FadeIn(tri_labels[0]),run_time=1.7)
        self.play(Create(triangle[1]),FadeIn(tri_labels[1]),run_time=1.7)
        self.play(d.probe.animate.set_value(1),run_time=1.5)
        self.play(d.probe.animate.set_value(2),run_time=2)
        self.say('يشير المجال الكهربائي في الاتجاه الذي ينخفض فيه الجهد')
        self.play(FadeOut(formula),FadeOut(d.guide),FadeOut(d.physical_dot),run_time=.7)
        field_eq = tex(r'E_x=-\frac{dV}{dx}=-2\;\mathrm{V/m}',35,BLUE).move_to([-3.5,-3.35,0])
        self.play(FadeIn(d.arrows),Write(field_eq),run_time=2)
        for y in (-1.1,1.1):
            flash = Line(d.P(2.7)+UP*y,d.P(.3)+UP*y,color=YELLOW,stroke_width=5)
            self.play(ShowPassingFlash(flash,time_width=.25),run_time=1.8)
        self.play(Indicate(d.left_label,color=GREEN),run_time=1.2)
        self.wait(1)
        self.beat('change_voltage')
        self.say('مع زيادة جهد اللوح، يزداد كل من الميل وشدة المجال')
        self.play(FadeOut(VGroup(triangle,tri_labels,field_eq)),run_time=.8)
        field_read = VGroup(tex(r'E_x=',28,BLUE),number(-2,28,BLUE),tex(r'\mathrm{V/m}',26,BLUE)).arrange(RIGHT,buff=.14).move_to([-3.4,-3.35,0])
        field_read[1].add_updater(lambda m:m.set_value(d.model.field(d.v1.get_value())))
        ghost = d.curve.copy().clear_updaters().set_color(GREY).set_opacity(.45)
        self.add(ghost)
        self.play(FadeIn(field_read),run_time=.7)
        self.play(d.v1.animate.set_value(9),run_time=4)
        self.play(d.probe.animate.set_value(1),run_time=2.2)
        self.play(d.probe.animate.set_value(2),run_time=2.2)
        self.play(d.v1.animate.set_value(6),run_time=3)
        self.beat('one_boundary_is_not_enough')
        self.say('معرفة الجهد عند طرف واحد لا تكفي لمعرفة كيف يتغير الجهد بين الطرفين')
        self.play(FadeOut(VGroup(d.arrows,field_read,d.probes(),ghost,d.right_label)),run_time=1)
        candidates = VGroup(*[Line(d.axes.c2p(0,0),d.axes.c2p(3,v),color=c,stroke_width=3) for v,c in [(3,GREY),(9,YELLOW)]])
        self.play(LaggedStart(*[Create(m) for m in candidates],lag_ratio=.45),run_time=2.5)
        question = tex(r'V(L)=\;?',33,YELLOW).move_to([-1.65,2.35,0])
        self.play(FadeIn(question),Indicate(d.left_label,color=GREEN),run_time=1.5)
        self.wait(1.5)
        self.say('عندما نعرف الجهد عند الطرفين، يتحدد الجهد بينهما')
        self.play(FadeOut(candidates),FadeOut(question),FadeIn(d.right_label),run_time=1.7)
        target = Dot(d.axes.c2p(3,6),color=BLUE,radius=.1)
        self.play(FadeIn(target),Circumscribe(d.right_label,color=BLUE),run_time=1.8)
        self.wait(2)
        self.finish()


if __name__ == '__main__':
    run(LaplaceOneDimension)
