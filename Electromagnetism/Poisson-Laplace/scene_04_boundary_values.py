from manim import *
from support34 import *
from settings34 import run


class BoundaryValues(LessonScene):
    def construct(self):
        self.beat('motion_initial_information')
        self.say('في الحركة نعرف الموضع والسرعة عند البداية')
        ax, frame = graph_axes([-3.7,.2,0],width=4.8,height=3.5,ymax=8,xlabel=r't\;(\mathrm{s})',ylabel=r's\;(\mathrm{m})')
        time = ValueTracker(0)
        curve = always_redraw(lambda:Line(ax.c2p(0,0),ax.c2p(max(.001,time.get_value()),2*max(.001,time.get_value())),color=GREEN,stroke_width=4))
        dot = always_redraw(lambda:Dot(ax.c2p(time.get_value(),2*time.get_value()),color=YELLOW,radius=.08))
        force = tex(r'm\frac{d^2s}{dt^2}=F(t)',44).move_to([3.25,1.7,0])
        initial = VGroup(tex(r's(t_0)=s_0',37,GREEN),tex(r'\frac{ds}{dt}(t_0)=u_0',37,YELLOW)).arrange(DOWN,buff=.6).move_to([3.25,-.1,0])
        self.play(Create(frame),Write(force),run_time=2.2)
        self.play(FadeIn(initial[0]),run_time=1.2)
        origin = Dot(ax.c2p(0,0),color=GREEN,radius=.1)
        self.play(FadeIn(origin),Indicate(initial[0],color=GREEN),run_time=1.5)
        tangent = Arrow(ax.c2p(0,0),ax.c2p(.9,1.8),buff=0,color=YELLOW,stroke_width=4)
        self.play(FadeIn(initial[1]),GrowArrow(tangent),run_time=1.8)
        tag = ar('شرطان عند اللحظة نفسها',27).move_to([3.2,-1.9,0])
        self.play(FadeIn(tag),run_time=1)
        self.wait(1.5)
        self.beat('constant_speed_motion')
        self.say('سرعة ثابتة مقدارها2  متر في الثانية')
        simple = tex(r'F=0\quad\Rightarrow\quad s(t)=(2\;\mathrm{m/s})t',36,GREEN).move_to([3.1,1.7,0])
        if simple.width>5.7: simple.scale_to_fit_width(5.7)
        starts = VGroup(tex(r't_0=0',30),tex(r's_0=0\;\mathrm{m}',30,GREEN),tex(r'u_0=2\;\mathrm{m/s}',30,YELLOW)).arrange(DOWN,buff=.35).move_to([3.2,-.1,0])
        self.play(FadeTransform(force,simple),FadeTransform(initial,starts),FadeOut(tag),run_time=1.5)
        track = Line([-6,-2.9,0],[6,-2.9,0],color=GREY,stroke_width=2)
        track_ticks = VGroup(*[VGroup(Line([x,-2.84,0],[x,-2.96,0],color=GREY),tex(str(v),21,GREY).move_to([x,-3.22,0])) for x,v in [(-6,0),(-2,2),(2,4),(6,6)]])
        ball = always_redraw(lambda:Dot([-6+4*time.get_value(),-2.9,0],radius=.14,color=GREEN))
        poslabel = tex(r's\;(\mathrm{m})',25).move_to([0,-3.65,0])
        clock = VGroup(tex(r't=',28),number(0,28,YELLOW),tex(r'\mathrm{s}',26)).arrange(RIGHT,buff=.15).move_to([3.2,-1.8,0])
        clock[1].add_updater(lambda m:m.set_value(time.get_value()))
        self.play(Create(track),FadeIn(track_ticks),FadeIn(poslabel),FadeIn(ball),FadeIn(clock),FadeOut(tangent),run_time=1.7)
        self.add(curve,dot)
        for t in (1,2,3):
            self.play(time.animate.set_value(t),run_time=3,rate_func=linear)
            point = Dot(ax.c2p(t,2*t),color=YELLOW,radius=.055)
            mark = tex(f'({t},{2*t})',22,YELLOW).next_to(point,UP+LEFT,buff=.12)
            self.play(FadeIn(point),FadeIn(mark),run_time=.65)
            self.wait(.6)
        self.say('هنا المحور الأفقي هو الزمن')
        self.play(Circumscribe(frame[1][0],color=YELLOW),run_time=1.5)
        self.wait(1.2)
        self.beat('spatial_boundary_values')
        self.play(*[FadeOut(m) for m in list(self.mobjects) if m is not self.caption],run_time=1.2)
        self.say('أما الجهد فنعرف قيمته عند موضعين')
        bx, bframe = graph_axes([2.8,.15,0],width=6.3,height=4,ymax=10)
        slope = ValueTracker(1)
        line = always_redraw(lambda:Line(bx.c2p(0,0),bx.c2p(3,3*slope.get_value()),color=BLUE,stroke_width=4))
        endpoint = always_redraw(lambda:Dot(bx.c2p(3,3*slope.get_value()),color=BLUE,radius=.09))
        start = Dot(bx.c2p(0,0),color=GREEN,radius=.1)
        target = Circle(radius=.13,color=YELLOW,stroke_width=3).move_to(bx.c2p(3,6))
        targetlabel = tex(r'V(3\;\mathrm{m})=6\;\mathrm{V}',27,YELLOW).move_to([3,2.65,0])
        fixed = VGroup(tex(r'V(0)=0\;\mathrm{V}',33,GREEN),tex(r'V(3\;\mathrm{m})=6\;\mathrm{V}',33,YELLOW)).arrange(DOWN,buff=.55).move_to([-4.2,.3,0])
        equation = tex(r'\frac{d^2V}{dx^2}=0',43).move_to([-4.2,2,0])
        self.play(Create(bframe),Write(equation),FadeIn(fixed[0]),FadeIn(start),run_time=2.3)
        self.play(FadeIn(fixed[1]),Create(target),FadeIn(targetlabel),run_time=1.6)
        self.play(Create(line),FadeIn(endpoint),run_time=2)
        trial = VGroup(tex(r'\frac{dV}{dx}=',29,BLUE),number(1,29,BLUE),tex(r'\mathrm{V/m}',26,BLUE)).arrange(RIGHT,buff=.15).move_to([-4.2,-1.4,0])
        trial[1].add_updater(lambda m:m.set_value(slope.get_value()))
        arrives = VGroup(tex(r'V(3\;\mathrm{m})=',27,BLUE),number(3,27,BLUE),tex(r'\mathrm{V}',26,BLUE)).arrange(RIGHT,buff=.15).move_to([-4.2,-2.35,0])
        arrives[1].add_updater(lambda m:m.set_value(3*slope.get_value()))
        error = always_redraw(lambda:Line(bx.c2p(3,3*slope.get_value()),bx.c2p(3,6)+UP*.00001,color=RED,stroke_width=5))
        self.play(FadeIn(trial),FadeIn(arrives),Create(error),run_time=1.5)
        self.say('في الرسم البياني للجهد بدلالة المسافة، يعني الميل الأصغر أن الجهد يتغير ببطء أكبر. وفي هذا المثال يصل الجهد إلى 3 فولت')
        self.play(Indicate(arrives,color=RED),Indicate(target,color=YELLOW),run_time=1.8)
        self.wait(1.5)
        self.beat('candidate_slopes')
        ghost1 = line.copy().clear_updaters().set_color(GREY).set_opacity(.35)
        self.add(ghost1)
        self.say('في حال كان الميل أكبر، يتغير الجهد بمقدار 9 فولت بدلاً من 3 فولت عبر المسافة ذاتها')
        self.play(slope.animate.set_value(3),run_time=4)
        self.play(Indicate(arrives,color=RED),run_time=1.5)
        self.wait(1.2)
        ghost2 = line.copy().clear_updaters().set_color(GREY).set_opacity(.35)
        self.add(ghost2)
        self.say('الخطان يحققان معادلة لابلاس، لكنهما يعطيان عند الطرف الثاني قيمة جهد تختلف عن القيمة المحددة')
        self.play(Circumscribe(equation,color=BLUE),run_time=1.8)
        self.play(Indicate(fixed[1],color=YELLOW),run_time=1.5)
        self.wait(1.2)
        self.say('عندما يكون الميل مساويا 2، يتحقق الشرطان كلاهما')
        self.play(slope.animate.set_value(2),run_time=4)
        self.play(FadeOut(error),FadeOut(ghost1),FadeOut(ghost2),Circumscribe(target,color=GREEN),run_time=1.8)
        result = tex(r'V(x)=(2\;\mathrm{V/m})x',35,BLUE).move_to([2.8,-3.1,0])
        self.play(Write(result),run_time=1.6)
        self.wait(1.5)
        self.beat('comparison')
        self.play(*[FadeOut(m) for m in list(self.mobjects) if m is not self.caption],run_time=1)
        self.say('المعادلة والشروط معاً يحدّدان الحل')
        la, lf = graph_axes([-3.7,-.25,0],width=4.8,height=2.8,ymax=8,xlabel=r't\;(\mathrm{s})',ylabel=r's\;(\mathrm{m})')
        ra, rf = graph_axes([3.65,-.25,0],width=4.8,height=2.8,ymax=8)
        heads = VGroup(ar('مسألة قيم ابتدائية',28,GREEN).move_to([-3.7,2.5,0]),ar('مسألة قيم حدية',28,BLUE).move_to([3.65,2.5,0]))
        ll = Line(la.c2p(0,0),la.c2p(3,6),color=GREEN,stroke_width=3)
        rl = Line(ra.c2p(0,0),ra.c2p(3,6),color=BLUE,stroke_width=3)
        lp = Dot(la.c2p(0,0),color=YELLOW,radius=.1)
        lt = Arrow(la.c2p(0,0),la.c2p(.85,1.7),buff=0,color=YELLOW,stroke_width=4)
        rp = VGroup(Dot(ra.c2p(0,0),color=YELLOW,radius=.1),Dot(ra.c2p(3,6),color=YELLOW,radius=.1))
        self.play(FadeIn(heads),Create(lf),Create(rf),run_time=2)
        self.play(Create(ll),Create(rl),run_time=2)
        self.play(FadeIn(lp),GrowArrow(lt),FadeIn(rp),run_time=2)
        notes = VGroup(ar('القيمة والميل عند زمن واحد',25).move_to([-3.7,-3.05,0]),ar('قيمتان عند موضعين',25).move_to([3.65,-3.05,0]))
        self.play(FadeIn(notes),run_time=1.3)
        self.play(Indicate(lp,color=YELLOW),Indicate(lt,color=YELLOW),run_time=1.6)
        self.play(Indicate(rp,color=YELLOW),run_time=1.6)
        self.wait(1.5)
        self.say('في الحركة نعرف موضع الجسم وسرعته عند لحظة البداية, أما الجهد فنعرف قيمته عند طرفي المنطقة لنحدد توزيعه بينهما')
        scan = ValueTracker(0)
        scanning = always_redraw(lambda:Dot(ra.c2p(scan.get_value(),2*scan.get_value()),color=WHITE,radius=.07))
        self.add(scanning)
        self.play(scan.animate.set_value(3),run_time=3)
        self.play(scan.animate.set_value(0),run_time=2.5)
        self.wait(1.5)
        self.finish()


if __name__ == '__main__':
    run(BoundaryValues)
