"""Run directly in PyCharm; POISSON_QUALITY=final selects 1080p60."""
import settings
from manim import *
from support import *

class CloudGround(OpeningScene):
    def construct(self):
        d=SlabDiagram()
        self.beat('cloud_ground_question')
        self.say('كيف نعرف المجال بين السحابة والأرض؟')
        cloud=VMobject(color=WHITE,stroke_width=3).set_points_smoothly([[-5.7,1.8,0],[-5.9,2.2,0],[-5.3,2.5,0],[-4.8,2.35,0],[-4.2,2.7,0],[-3.5,2.5,0],[-2.8,2.65,0],[-2.2,2.3,0],[-1.3,2.3,0],[-.85,1.9,0],[-1.3,1.6,0],[-5.7,1.8,0]])
        minus=VGroup(*[Line([x-.12,2.02,0],[x+.12,2.02,0],color=BLUE,stroke_width=3) for x in (-5,-4,-3,-2)])
        ground=d.boundaries[0].copy(); plus=d.charges[:7].copy()
        vl=VGroup(tex('V_1',32,color=BLUE).move_to([-.1,2,0]),tex('V_0',32).move_to([-.1,-2.2,0]))
        self.play(Create(cloud),Create(ground),run_time=2.5)
        self.play(LaggedStart(*[FadeIn(m) for m in minus],lag_ratio=.3),FadeIn(plus),FadeIn(vl),run_time=2)
        region=Rectangle(width=3.1,height=2.4,color=BLUE,stroke_width=1.5,fill_color=BLUE,fill_opacity=.035).move_to([-3.3,-.2,0])
        air=ar('منطقة من الهواء',27).move_to([3,.8,0]); free=ar('لا شحنات حرّة في الداخل',27).move_to([3,0,0])
        pointer=Line([1,.4,0],[-1.7,.2,0],color=GREY)
        self.play(Create(region),FadeIn(air),Create(pointer),run_time=2)
        self.play(FadeIn(free),run_time=1.5); self.wait(2.5)
        self.say('\u202Bنفترض أن السحابة مشحونة و يكون جهدها \u2066"V1"\u2069، بالنسبة إلى جهد الأرض \u2066"V0"\u2069\u202C')
        self.play(Indicate(region,color=BLUE),run_time=2); self.wait(2)
        self.beat('planar_boundaries_and_potential')
        self.say('يمكننا تبسيط النموذج إلى سحابة وأرض كما هو موضح في الرسم')
        self.play(FadeOut(VGroup(cloud,minus,ground,plus,vl,region,air,free,pointer)),FadeIn(d.field()),run_time=2.5)
        self.play(Create(d.levels),FadeIn(d.level_values),FadeIn(d.height_axis),run_time=2)
        defs=VGroup(ar('الجهد الكهربائي',25),tex('V',31,color=BLUE)).arrange(RIGHT,buff=.3).move_to([3.4,.5,0])
        self.play(FadeIn(defs),run_time=1.2); self.wait(1.8)
        self.play(FadeOut(defs),Create(d.axes),FadeIn(d.axis_labels),FadeIn(d.ticks),run_time=2)
        self.play(Create(d.curve),run_time=2)
        self.play(FadeIn(d.dot),FadeIn(d.graph_dot),FadeIn(d.crosshair),FadeIn(d.readout),run_time=1)
        self.say('نقوم بتحريك نقطة القياس إلى الأعلى ونسجّل الجهد عند كل ارتفاع')
        self.play(d.probe.animate.set_value(2.8),run_time=6,rate_func=linear)
        self.play(d.probe.animate.set_value(1.5),run_time=3,rate_func=smooth)
        self.beat('negative_gradient_and_direction')
        self.say('ينخفض الجهد كلما اتجهت إلى الأعلى، لذا يشير المجال الكهربائي إلى الأعلى')
        eq=tex(r'\mathbf{E}=-\nabla V',42).move_to([3.5,-3.25,0])
        self.play(FadeIn(eq),FadeIn(d.arrows),run_time=2)
        guide=ar('توضيح اتجاه المجال الكهربائي',22,color=YELLOW).move_to([-3.2,-3.15,0])
        self.play(FadeIn(guide),run_time=.7)
        self.play(*[ShowPassingFlash(Line([x,d.Y(.15),0],[x,d.Y(2.8),0],color=YELLOW,stroke_width=5),time_width=.28) for x in (-5.1,-3.8,-2.5,-1.3)],run_time=3)
        self.play(FadeOut(guide),run_time=.7); self.wait(1.5)
        self.beat('boundary_voltage_controls_gradient')
        self.say('إذا زاد فرق الجهد بين لوحين وبقيت المسافة بينهما ثابتة، زادت شدة المجال الكهربائي بينهما')
        self.play(Indicate(d.vtop,color=YELLOW),run_time=1.5)
        self.play(d.vc.animate.set_value(-6),run_time=6,rate_func=smooth)
        self.play(d.probe.animate.set_value(2.7),run_time=3,rate_func=linear)
        self.wait(2)
        self.beat('finite_difference_to_field')
        self.say('نحسب مقدار تغير الجهد الكهربائي عندما يتغير الارتفاع')
        self.play(FadeOut(d.dot),FadeOut(d.graph_dot),FadeOut(d.crosshair),FadeOut(d.readout),FadeOut(eq),run_time=1)
        p1=d.axes.c2p(1,-2);p2=d.axes.c2p(2,-4); elbow=d.axes.c2p(2,-2)
        triangle=VGroup(Line(p1,elbow,color=YELLOW),Line(elbow,p2,color=YELLOW),Dot(p1,color=YELLOW),Dot(p2,color=YELLOW))
        labs=VGroup(tex(r'\Delta y=1',25,color=YELLOW).next_to(triangle[0],UP,buff=.18),tex(r'\Delta V=-2',25,color=YELLOW).next_to(triangle[1],RIGHT,buff=.18))
        self.play(Create(triangle),run_time=2);self.play(FadeIn(labs),run_time=1.5)
        calc=tex(r'E_y=-\frac{\Delta V}{\Delta y}=-\frac{-2}{1}=2',34).move_to([3.4,-2.85,0])
        self.play(FadeIn(calc),run_time=2);self.wait(2.5)
        self.play(Indicate(triangle[0],color=YELLOW),Indicate(triangle[1],color=YELLOW),run_time=2)
        self.say('إذا عرفنا الجهد عند كل نقطة، فيمكننا تحديد المجال الكهربائي')
        self.play(FadeOut(triangle),FadeOut(labs),FadeOut(calc),run_time=1.5)
        final=tex(r'V(y)\quad\longrightarrow\quad E_y=-\frac{dV}{dy}',36).move_to([3.3,-2.85,0])
        self.play(FadeIn(final),run_time=2); self.wait(2.5)
        self.finish()

if __name__=='__main__': settings.run(CloudGround)
